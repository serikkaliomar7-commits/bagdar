/* =========================================================
   Қабілет тапсырмалары — 5 қиындық деңгейі.
   Домендер DAT / GATB дәстүрлі батареяларына сай:
   логика, сандар, мәтін, кеңістік, механика (+ кеңсе жылдамдығы).
   Көбі генерацияланады: әр оқушыға жаңа тапсырма, жауапты «көшіру» мүмкін емес.
   ========================================================= */
const R = (a, b) => a + Math.floor(Math.random() * (b - a + 1));
const pick = a => a[Math.floor(Math.random() * a.length)];
const shuffle = a => { a = [...a]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };
const fmtN = n => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");

/* Сандық жауап: 4 бірегей нұсқа, дұрысы кездейсоқ орында */
function numOptions(ans, distractors, unit = "") {
  const set = [ans];
  for (const d of distractors) if (!set.includes(d) && d >= 0 && set.length < 4) set.push(d);
  let k = 1; while (set.length < 4) { const d = ans + k * (k % 2 ? 1 : -1) * Math.max(1, Math.round(Math.abs(ans) * 0.1)); if (!set.includes(d) && d >= 0) set.push(d); k++; }
  const o = shuffle(set);
  return { o: o.map(x => fmtN(x) + unit), a: o.indexOf(ans) };
}

/* ---------------- ЛОГИКА: сандар тізбегі ---------------- */
function seq(level) {
  let s, ans, wrong, tpl = "seq" + level;
  if (level === 1) { const a = R(1, 20), d = R(2, 9); s = [0, 1, 2, 3, 4].map(i => a + i * d); ans = a + 5 * d; wrong = [ans + d, ans - 1, ans + 2]; }
  else if (level === 2) {
    if (Math.random() < .5) { tpl = "seq2geo"; const a = R(1, 6); s = [0, 1, 2, 3, 4].map(i => a * 2 ** i); ans = a * 32; wrong = [ans - a * 16 / 2, a * 16 + a * 8, ans + 2]; }
    else { tpl = "seq2dec"; const a = R(15, 30), d = R(4, 8); s = [0, 1, 2, 3, 4].map(i => a - i * d); ans = a - 5 * d; wrong = [ans + d, ans - 1, -ans]; }
  } else if (level === 3) { const a = R(1, 10), d = R(1, 4), st = R(1, 3); s = [a]; for (let i = 0; i < 4; i++) s.push(s[i] + d + i * st); ans = s[4] + d + 4 * st; wrong = [s[4] + d + 3 * st, ans + st, ans - 1]; }
  else if (level === 4) { const a = R(1, 9), p = R(2, 5), b = R(20, 40), q = R(2, 5); s = []; for (let i = 0; i < 6; i++) s.push(i % 2 ? b - Math.floor(i / 2) * q : a + (i / 2) * p); ans = a + 3 * p; wrong = [b - 3 * q, ans + p, s[5] - q]; }
  else {
    if (Math.random() < .5) { tpl = "seq5fib"; const x = R(1, 5), y = R(2, 6); s = [x, y]; for (let i = 2; i < 6; i++) s.push(s[i - 1] + s[i - 2]); ans = s[4] + s[5]; wrong = [s[5] + (s[5] - s[4]), ans + 1, s[5] * 2]; }
    else { tpl = "seq5dbl"; const a = R(1, 3); s = [a]; for (let i = 1; i < 5; i++) s.push(s[i - 1] * 2 + 1); ans = s[4] * 2 + 1; wrong = [s[4] * 2, ans + 2, s[4] + (s[4] - s[3]) * 2 - 1]; }
  }
  const { o, a } = numOptions(ans, wrong);
  const list = s.join(", ") + ", ?";
  return { q: { kk: `Тізбекті жалғастыр: ${list}`, ru: `Продолжи ряд: ${list}` }, o, a, tpl };
}

/* ---------------- САНДАР: мәтінді есептер ---------------- */
function num(level) {
  if (level === 1) {
    const p = pick([10, 20, 25, 50]), N = R(2, 20) * 20, ans = N * p / 100;
    return { q: { kk: `${fmtN(N)} санының ${p}%-ы қанша?`, ru: `Сколько будет ${p}% от ${fmtN(N)}?` }, ...numOptions(ans, [N - ans, ans * 2, ans + p]) };
  }
  if (level === 2) {
    const P = R(10, 200) * 100, p = pick([10, 20, 25, 30]), ans = P * (100 - p) / 100;
    return { q: { kk: `Тауардың бағасы ${fmtN(P)} ₸. Оған ${p}% жеңілдік берілді. Жаңа бағасы қанша?`,
                  ru: `Товар стоит ${fmtN(P)} ₸. На него скидка ${p}%. Сколько он стоит теперь?` },
             ...numOptions(ans, [P * p / 100, P - p, ans + P / 10], " ₸") };
  }
  if (level === 3) {
    const p = pick([10, 20, 30]), q = pick([10, 20, 30, 50]), ans = 100 - (100 - p) * (100 - q) / 100;
    return { q: { kk: `Тауарға алдымен ${p}%, сосын тағы ${q}% жеңілдік берілді. Ол барлығы неше пайызға арзандады?`,
                  ru: `На товар сначала дали скидку ${p}%, потом ещё ${q}%. На сколько процентов он подешевел всего?` },
             ...numOptions(ans, [p + q, ans - 2, ans + 5], "%") };
  }
  if (level === 4) {
    let a, b, t, ans;
    do { a = R(2, 8); b = R(2, 12); ans = R(2, 12); t = ans * b / a; } while (a === b || !Number.isInteger(t));
    return { q: { kk: `${a} жұмысшы жұмысты ${t} сағатта бітіреді. ${b} жұмысшы осы жұмысты неше сағатта бітіреді?`,
                  ru: `${a} рабочих выполняют работу за ${t} ч. За сколько часов эту работу выполнят ${b} рабочих?` },
             ...numOptions(ans, [Math.round(t * b / a), t, t + b - a], "") };
  }
  const p = pick([10, 20, 30, 40]), ans = p * p / 100;
  const pc = x => String(x).replace(".", ",") + "%";                // ондық бөлшек — үтірмен
  const opts = shuffle([`−${pc(ans)}`, "0%", `+${pc(ans)}`, `−${pc(ans / 2)}`]);
  return { q: { kk: `Баға ${p}%-ға өсті, сосын ${p}%-ға төмендеді. Бастапқы бағамен салыстырғанда ол қалай өзгерді?`,
                ru: `Цена выросла на ${p}%, а потом снизилась на ${p}%. Как она изменилась по сравнению с исходной?` },
           o: opts, a: opts.indexOf(`−${pc(ans)}`) };
}


function verbal(level, used) {
  const pool = V.filter(v => !used.has(v));
  const best = pool.filter(v => v.l === level);
  const v = best.length ? pick(best) : pool.sort((x, y) => Math.abs(x.l - level) - Math.abs(y.l - level))[0];
  used.add(v);
  const order = shuffle(v.o.map((_, i) => i));
  return { q: v.q, o: order.map(i => v.o[i]), a: order.indexOf(v.a), level: v.l, tpl: "verbal" + V.indexOf(v) };
}

/* ---------------- КЕҢІСТІК: айналдыру (хиралды полиомино) ---------------- */
const rot = c => c.map(([x, y]) => [y, -x]);
const mir = c => c.map(([x, y]) => [-x, y]);
const norm = c => { const mx = Math.min(...c.map(p => p[0])), my = Math.min(...c.map(p => p[1]));
  return c.map(([x, y]) => [x - mx, y - my]).sort((a, b) => a[0] - b[0] || a[1] - b[1]); };
const key = c => JSON.stringify(norm(c));
const rots = c => [c, rot(c), rot(rot(c)), rot(rot(rot(c)))];
function polyomino(n) {
  for (;;) {
    const cells = [[0, 0]];
    while (cells.length < n) {
      const [x, y] = pick(cells), [dx, dy] = pick([[1, 0], [-1, 0], [0, 1], [0, -1]]);
      if (!cells.some(c => c[0] === x + dx && c[1] === y + dy)) cells.push([x + dx, y + dy]);
    }
    const r = new Set(rots(cells).map(key));
    if (r.size === 4 && !r.has(key(mir(cells))) && Math.max(...norm(cells).map(c => Math.max(c[0], c[1]))) <= 4) return cells;  // хиралды, айналу симметриясы жоқ → 4 бірегей нұсқа
  }
}
function spatial(level) {
  const base = polyomino(3 + level);                       // 4…8 шаршы
  const correct = rots(base)[R(1, 3)];
  const mirrors = shuffle(rots(mir(base))).filter((c, i, a) => a.findIndex(x => key(x) === key(c)) === i).slice(0, 3);
  const o = shuffle([correct, ...mirrors]);
  return { q: { kk: "Қай фигура — үлгінің айналдырылған нұсқасы (айнадағы бейнесі емес)?",
                ru: "Какая фигура — та же, что образец, только повёрнутая (не зеркальная)?" },
           fig: { base, opts: o }, o: o.map((_, i) => "ABCD"[i]), a: o.indexOf(correct), tpl: "rot" + base.length };
}


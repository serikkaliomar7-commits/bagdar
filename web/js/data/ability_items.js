/* ---------------- КЕҢСЕ ЖЫЛДАМДЫҒЫ: 45 секунд «бірдей / әртүрлі» ---------------- */
const CH = "ABCEHKMPTX0123456789";
export function clericalPair() {
  const code = () => Array.from({ length: R(6, 8) }, () => pick([...CH])).join("");
  const a = code().replace(/^(.{2})(.{3})/, "$1-$2-");
  if (Math.random() < .5) return { a, b: a, same: true };
  const i = pick([...a].map((c, k) => c === "-" ? -1 : k).filter(k => k >= 0));
  let c; do { c = pick([...CH]); } while (c === a[i]);
  return { a, b: a.slice(0, i) + c + a.slice(i + 1), same: false };
}

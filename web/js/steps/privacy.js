export function privacy(app, { go }) {
  document.getElementById("progress").hidden = true;
  const T = TXT[getLang()] || TXT.ru;
  app.append(screen(h("div", { class: "prose" },
    h("h1", { class: "title" }, T.title),
    T.sections.flatMap(([title, body]) => [h("h2", {}, title), h("p", {}, body)]),
    CONFIG.CONTACT_EMAIL && [h("h2", {}, T.contact), h("p", {}, h("a", { href: "mailto:" + CONFIG.CONTACT_EMAIL }, CONFIG.CONTACT_EMAIL))]),
    deleteBlock(go),
    h("div", { class: "actions" }, h("button", { class: "btn btn--ghost", onclick: () => history.length > 1 ? history.back() : go("home") }, "←"))));
}
